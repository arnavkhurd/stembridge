type Translate = (
  key: string,
  values?: Record<string, string | number>,
) => string;

// More literal wording wins: a short template must not capture the explanatory
// suffix of a longer one as if that suffix were a skill name.
const authoredTemplates = Object.keys(contentMarathi)
  .filter((key) => /\{\w+\}/.test(key))
  .sort(
    (a, b) =>
      b.replace(/\{\w+\}/g, "").length - a.replace(/\{\w+\}/g, "").length,
  );

/** Only pass application-generated copy here, never a member's text. */
export function translateAuthoredText(text: string, t: Translate): string {
  const direct = t(text);
  if (direct !== text) return direct;
  for (const key of authoredTemplates) {
    const names = [...key.matchAll(/\{(\w+)\}/g)].map((match) => match[1]);
    if (!names.length) continue;
    const escaped = key.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const pattern = escaped.replace(/\\\{\w+\\\}/g, "(.+?)");
    const match = text.match(new RegExp(`^${pattern}$`));
    if (!match) continue;
    const values = Object.fromEntries(
      names.map((name, index) => [
        name,
        match[index + 1]
          .split(", ")
          .map((value) => t(value))
          .join(", "),
      ]),
    );
    return t(key, values);
  }
  return direct;
}
